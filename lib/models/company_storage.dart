void mergeDynamicCompanies(List<CompanyStorage> dynamicCompanies) {
  for (var dyn in dynamicCompanies) {
    if (dyn.isDeleted) {
      kCompanyStorages.removeWhere((c) =>
        c.name.toLowerCase() == dyn.name.toLowerCase() ||
        c.aliases.any((a) => a.toLowerCase() == dyn.name.toLowerCase())
      );
    } else {
      final idx = kCompanyStorages.indexWhere((c) =>
        c.name.toLowerCase() == dyn.name.toLowerCase() ||
        c.aliases.any((a) => a.toLowerCase() == dyn.name.toLowerCase())
      );
      if (idx == -1) {
        kCompanyStorages.add(dyn);
      } else {
        kCompanyStorages[idx] = dyn;
      }
    }
  }
}

void removeCompanyFromStorage(String companyName) {
  kCompanyStorages.removeWhere((c) =>
    c.name.toLowerCase() == companyName.toLowerCase() ||
    c.aliases.any((a) => a.toLowerCase() == companyName.toLowerCase())
  );
}
